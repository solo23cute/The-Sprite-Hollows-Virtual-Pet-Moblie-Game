function registerAdultSwimRoster(roster, keysOut) {
  roster.forEach(([key, name, geneKey, palette, price, blurb, greeting], index) => {
    const gene = ADULTSWIM_GENES[geneKey] || ADULTSWIM_GENES.weird;
    const [primary, light, deep, accent] = palette;
    ELEMENTS[key] = {
      name, primary, light, deep, accent,
      trait: `${gene[0]} — ${gene[2]}`,
      blurb,
      greeting,
      likes: ['Late Night Nachos', 'Star Cookie', 'Berry Fizz', 'Milk Tea', 'Honeycomb Cake', 'Lemonade', 'Candyfloss', 'Sun Nectar', 'Trail Mix', 'Moon Berry'][index % 10],
      adultswim: true,
    };
    GENE_POWERS[key] = { name: gene[0], icon: gene[1], desc: gene[2], effect: gene[3] };
    TITAN_NAMES[key] = `${name} Titan`;
    NAME_START[key] = [name.split(' ')[0], 'Static', 'Midnight', 'Signal', 'Channel', 'Static'];
    TYPE_EGG_BASE_PRICE[key] = price;
    TYPE_EGG_PRICE[key] = discountedEggPrice(price);
    (ADULTSWIM_HOMES[geneKey] || ['neon']).forEach((scene) => {
      if (SCENES[scene] && !SCENES[scene].species.includes(key)) SCENES[scene].species.push(key);
    });
    keysOut.push(key);
  });
}

