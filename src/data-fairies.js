function registerFairyRoster(roster, flag, keysOut) {
  roster.forEach(([key, name, talentKey, palette, price, blurb, greeting], index) => {
    const talent = FAIRY_TALENTS[talentKey] || FAIRY_TALENTS.wish;
    const [primary, light, deep, accent] = palette;
    ELEMENTS[key] = {
      name, primary, light, deep, accent,
      trait: `${talent[0]} talent — ${talent[2]}`,
      blurb,
      greeting,
      likes: ['Honey Drop', 'Moon Berry', 'Pixie Pear', 'Star Cookie', 'Berry Fizz', 'Lemonade', 'Sun Nectar', 'Candyfloss', 'Trail Mix', 'Milk Tea'][index % 10],
      [flag]: true,
    };
    GENE_POWERS[key] = { name: `${talent[0]} Talent`, icon: talent[1], desc: talent[2], effect: talent[3] };
    TITAN_NAMES[key] = `${name} Titan`;
    NAME_START[key] = [name.split(' ')[0], 'Pixie', 'Hollow', 'Flutter', 'Dust', 'Petal'];
    TYPE_EGG_BASE_PRICE[key] = price;
    TYPE_EGG_PRICE[key] = discountedEggPrice(price);
    (FAIRY_HOMES[talentKey] || ['grove']).forEach((scene) => {
      if (SCENES[scene] && !SCENES[scene].species.includes(key)) SCENES[scene].species.push(key);
    });
    keysOut.push(key);
  });
}

